async function seedDatabase(dbInstance = null) {
    let db = dbInstance;
    let ownDb = false;

    if (!db) {
        const SQL = await initSqlJs();
        const baseStorageDir = process.env.VERCEL ? '/tmp' : __dirname;
        const dbPath = path.join(baseStorageDir, '..', 'database', 'liquid_music.db');
        if (fs.existsSync(dbPath)) {
            const buffer = fs.readFileSync(dbPath);
            db = new SQL.Database(buffer);
        } else {
            db = new SQL.Database();
        }
        ownDb = true;
    }

    // Ensure schema is applied
    const schemaPath = path.join(__dirname, 'schema.sql');
    if (fs.existsSync(schemaPath)) {
        db.run(fs.readFileSync(schemaPath, 'utf8'));
    }

    let inserted = 0;
    let updated = 0;

    const stmt = db.prepare(`
        INSERT INTO songs (
            id, title, artist, album, duration, audio_url, cover_url,
            language, mood, vibe_tags, energy, tempo_bpm, genre, release_year,
            hero_actor, heroine, music_director, singer, movie
        ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        ON CONFLICT(id) DO UPDATE SET
            title=excluded.title,
            artist=excluded.artist,
            album=excluded.album,
            duration=excluded.duration,
            audio_url=excluded.audio_url,
            cover_url=excluded.cover_url,
            language=excluded.language,
            mood=excluded.mood,
            vibe_tags=excluded.vibe_tags,
            energy=excluded.energy,
            tempo_bpm=excluded.tempo_bpm,
            genre=excluded.genre,
            release_year=excluded.release_year,
            hero_actor=excluded.hero_actor,
            heroine=excluded.heroine,
            music_director=excluded.music_director,
            singer=excluded.singer,
            movie=excluded.movie
    `);

    for (const song of SAMPLE_SONGS) {
        stmt.run([
            song.id,
            song.title,
            song.artist,
            song.album,
            song.duration,
            song.audio_url,
            song.cover_url,
            song.language,
            song.mood,
            song.vibe_tags,
            song.energy,
            song.tempo_bpm,
            song.genre,
            song.release_year,
            song.hero_actor,
            song.heroine,
            song.music_director,
            song.singer,
            song.movie
        ]);
        inserted++;
    }
    stmt.free();

    console.log(`[SeedSongs] Successfully seeded ${inserted} songs with full metadata.`);

    if (ownDb) {
        const baseStorageDir = process.env.VERCEL ? '/tmp' : __dirname;
        const dbPath = path.join(baseStorageDir, '..', 'database', 'liquid_music.db');
        const data = db.export();
        fs.writeFileSync(dbPath, Buffer.from(data));
        console.log(`[SeedSongs] Database saved to ${dbPath}`);
    }

    return inserted;
}

if (require.main === module) {
    seedDatabase().catch(err => {
        console.error('[SeedSongs] Failed to seed database:', err);
        process.exit(1);
    });
}

